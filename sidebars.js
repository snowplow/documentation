/**
 * The docs have four sidebars, all served by the one docs plugin so that
 * every /docs/... URL stays the same:
 *
 * - cdi: Snowplow CDI, grouped by what the reader is doing
 * - signals: Snowplow Signals
 * - reference: lookup material, plus every previous-versions tree under Legacy
 * - platform: deploying, running, and administering Snowplow, and AI tooling
 *   (Platform & AI in the navbar)
 *
 * Each top-level group is a section header; a pick at the top level is an
 * unheaded page. `pick(path)` pulls a directory
 * (or a single page) out of docs/ with its autogenerated children; see
 * utils/sidebar-items-generator.js for the options. A doc belongs to the
 * sidebar that lists it, and the navbar tabs follow that sidebar.
 *
 * Run `node utils/check-sidebars.js` after a build to check that every page
 * is in exactly one sidebar.
 */

const path = require('path')

/**
 * Pick a directory or page from docs/, with its autogenerated children.
 * @param {string} docsPath path relative to docs/, without extension
 * @param {{label?: string, hoist?: boolean, indexOnly?: boolean, indexLabel?: string, className?: string, collapsed?: boolean, customProps?: object, exclude?: string[]}} [opts]
 * `hoist` lists the directory's children directly, with its index page first
 * (labeled `indexLabel`). `indexOnly` takes just the directory's index page,
 * for when its children are picked one by one. `exclude` drops docs paths
 * from the picked tree, for pages listed in another group.
 */
const pick = (docsPath, opts = {}) => ({
  type: 'autogenerated',
  dirName: path.posix.dirname(docsPath),
  customProps: { pick: { path: docsPath, ...opts } },
})

/** A top-level group label in the sidebar */
const group = (label, items, { collapsible = false, collapsed = false } = {}) => ({
  type: 'category',
  label,
  className: 'section-header',
  collapsible,
  collapsed,
  items,
})

/**
 * A category that groups picks which share no directory. Collapsed unless
 * `collapsed: false`; the active-page auto-expand opens it either way.
 */
const sub = (label, items, { collapsed = true } = {}) => ({
  type: 'category',
  label,
  collapsible: true,
  collapsed,
  items,
})

